  function paintCap(name, fill, stroke, on, live) {
    const obj = document.querySelector('#pxCapObj rect');
    const label = document.getElementById('pxCapObjT');
    const out = document.getElementById('pxCapOut');
    const line = document.getElementById('pxCapLive');
    if (obj) { obj.setAttribute('fill', fill); obj.setAttribute('stroke', stroke); }
    if (label) {
      label.textContent = name;
      label.setAttribute('fill', name === 'пусто' ? '#64748b' : '#1e293b');
    }
    if (out) {
      out.textContent = on ? 'выход есть' : 'выхода нет';
      out.setAttribute('fill', on ? '#166534' : '#991b1b');
    }
    if (line) {
      line.textContent = live;
      line.style.color = on ? '#166534' : '#991b1b';
    }
  }

